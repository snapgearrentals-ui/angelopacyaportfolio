/* ========================================
   ESC KEY
======================================== */

document.addEventListener(
    "keydown",
    function (event) {

        if (
            event.key === "Escape"
        ) {

            if (
                lightbox.classList.contains(
                    "active"
                )
            ) {

                closeImageLightbox();

            } else {

                closeProject();

            }

        }

    }
);
