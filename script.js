/* =========================================================
   CREATE MODAL
========================================================= */

function createProjectModal() {

  if (document.getElementById("apProjectModal")) {
    return;
  }

  const modal = document.createElement("div");

  modal.id = "apProjectModal";

  modal.innerHTML = `

    <div class="ap-modal-backdrop"></div>

    <div class="ap-modal-window">

      <button
        class="ap-modal-close"
        type="button"
        aria-label="Close"
      >×</button>

      <div class="ap-modal-category"></div>

      <h2 class="ap-modal-title"></h2>

      <p class="ap-modal-description"></p>

      <div class="ap-modal-gallery-label">
        <span>SELECTED WORK</span>
        <span class="ap-modal-count"></span>
      </div>

      <div class="ap-modal-gallery"></div>

    </div>
  `;

  document.body.appendChild(modal);


  modal
    .querySelector(".ap-modal-close")
    .addEventListener("click", closeProject);


  modal
    .querySelector(".ap-modal-backdrop")
    .addEventListener("click", closeProject);

}


/* =========================================================
   OPEN PROJECT
========================================================= */

function openProject(projectKey) {

  const project = PROJECTS[projectKey];

  if (!project) {
    console.log("No project found:", projectKey);
    return;
  }

  createProjectModal();

  const modal =
    document.getElementById("apProjectModal");

  const category =
    modal.querySelector(".ap-modal-category");

  const title =
    modal.querySelector(".ap-modal-title");

  const description =
    modal.querySelector(".ap-modal-description");

  const gallery =
    modal.querySelector(".ap-modal-gallery");

  const count =
    modal.querySelector(".ap-modal-count");


  category.textContent =
    project.category;

  title.textContent =
    project.title;

  description.textContent =
    project.description;


  gallery.innerHTML = "";


  if (!project.media || project.media.length === 0) {

    gallery.innerHTML = `

      <div class="ap-modal-empty">

        <strong>
          Project details coming together.
        </strong>

        <p>
          More selected work from this project will be added here.
        </p>

      </div>

    `;

    count.textContent = "";

  } else {

    count.textContent =
      project.media.length + " pieces";


    project.media.forEach(
      (media, index) => {

        const type = media[0];
        const id = media[1];

        const item =
          document.createElement("div");

        item.className =
          "ap-modal-media";


        if (type === "image") {

          item.innerHTML = `

            <img
              src="${driveImage(id)}"
              alt="${project.title} project image ${index + 1}"
              loading="lazy"
            >

            <div class="ap-modal-media-overlay">
              <span>View image ↗</span>
            </div>

          `;


          const image =
            item.querySelector("img");


          image.onerror = function() {

            this.src =
              "https://drive.google.com/uc?export=view&id=" + id;

          };


          item.addEventListener(
            "click",
            function() {
              openLightbox(id);
            }
          );

        }


        if (type === "video") {

          item.innerHTML = `

            <iframe
              class="ap-modal-video"
              src="https://drive.google.com/file/d/${id}/preview"
              allow="autoplay"
              allowfullscreen
              loading="lazy"
              title="Project video"
            ></iframe>

          `;

        }


        gallery.appendChild(item);

      }
    );

  }


  modal.classList.add("active");

  document.body.style.overflow = "hidden";

}


/* =========================================================
   CLOSE PROJECT
========================================================= */

function closeProject() {

  const modal =
    document.getElementById("apProjectModal");

  if (!modal) return;

  modal.classList.remove("active");

  document.body.style.overflow = "";

}


/* =========================================================
   LIGHTBOX
========================================================= */

function createLightbox() {

  if (document.getElementById("apLightbox")) {
    return;
  }

  const lightbox =
    document.createElement("div");

  lightbox.id =
    "apLightbox";

  lightbox.innerHTML = `

    <button
      class="ap-lightbox-close"
      type="button"
    >×</button>

    <img
      alt="Project image"
    >

  `;

  document.body.appendChild(lightbox);


  lightbox
    .querySelector(".ap-lightbox-close")
    .addEventListener(
      "click",
      closeLightbox
    );


  lightbox.addEventListener(
    "click",
    function(event) {

      if (event.target === lightbox) {
        closeLightbox();
      }

    }
  );

}


function openLightbox(id) {

  createLightbox();

  const lightbox =
    document.getElementById("apLightbox");

  const image =
    lightbox.querySelector("img");

  image.src =
    driveImage(id);

  image.onerror = function() {

    this.src =
      "https://drive.google.com/uc?export=view&id=" + id;

  };

  lightbox.classList.add("active");

}


function closeLightbox() {

  const lightbox =
    document.getElementById("apLightbox");

  if (!lightbox) return;

  lightbox.classList.remove("active");

}


/* =========================================================
   IMPORTANT:
   UNIVERSAL PROJECT CLICK HANDLER
========================================================= */

document.addEventListener(
  "click",
  function(event) {

    /*
      Look for the closest project card
      from whatever element was clicked.
    */

    const card =
      event.target.closest(
        ".work-card[data-project]"
      );


    if (!card) {
      return;
    }


    const projectKey =
      card.getAttribute("data-project");


    if (!projectKey) {
      return;
    }


    /*
      Don't interfere with navigation
      inside the project modal itself.
    */

    if (
      event.target.closest(
        "#apProjectModal"
      )
    ) {
      return;
    }


    event.preventDefault();
    event.stopPropagation();


    openProject(projectKey);

  },
  true
);


/* =========================================================
   ALSO SUPPORT VIEW PROJECT ELEMENTS
========================================================= */

document.addEventListener(
  "click",
  function(event) {

    const viewButton =
      event.target.closest(
        ".work-overlay, .work-overlay *, [data-view-project]"
      );


    if (!viewButton) {
      return;
    }


    const card =
      viewButton.closest(
        ".work-card[data-project]"
      );


    if (!card) {
      return;
    }


    const projectKey =
      card.getAttribute("data-project");


    if (!projectKey) {
      return;
    }


    event.preventDefault();
    event.stopPropagation();


    openProject(projectKey);

  },
  true
);


/* =========================================================
   ESCAPE KEY
========================================================= */

document.addEventListener(
  "keydown",
  function(event) {

    if (event.key === "Escape") {

      closeLightbox();
      closeProject();

    }

  }
);


/* =========================================================
   LOAD COVER IMAGES
========================================================= */

function loadCoverImages() {

  document
    .querySelectorAll(
      ".work-card[data-project]"
    )
    .forEach(card => {

      const key =
        card.getAttribute("data-project");

      const project =
        PROJECTS[key];


      if (
        !project ||
        !project.cover
      ) {
        return;
      }


      const image =
        card.querySelector(
          "img"
        );


      if (!image) {
        return;
      }


      image.src =
        driveImage(project.cover);


      image.onerror =
        function() {

          this.src =
            "https://drive.google.com/uc?export=view&id=" +
            project.cover;

        };

    });

}


/* =========================================================
   SMOOTH SCROLL
========================================================= */

function setupSmoothScroll() {

  document
    .querySelectorAll(
      'a[href^="#"]'
    )
    .forEach(link => {

      link.addEventListener(
        "click",
        function(event) {

          const href =
            this.getAttribute("href");


          if (
            !href ||
            href === "#"
          ) {
            return;
          }


          const target =
            document.querySelector(
              href
            );


          if (!target) {
            return;
          }


          event.preventDefault();


          target.scrollIntoView({
            behavior: "smooth",
            block: "start"
          });

        }
      );

    });

}


