/* ========================================
   GET GOOGLE DRIVE FILE ID
======================================== */

function getDriveFileId(url) {

    const match = url.match(
        /\/d\/([a-zA-Z0-9_-]+)/
    );

    return match ? match[1] : null;
}


/* ========================================
   GET GOOGLE DRIVE IMAGE URL
======================================== */

function getDriveImageUrl(url) {

    const fileId = getDriveFileId(url);

    if (!fileId) {
        return null;
    }

    return `https://drive.google.com/thumbnail?id=${fileId}&sz=w1600`;
}


/* ========================================
   GET GOOGLE DRIVE VIDEO URL
======================================== */

function getDriveVideoUrl(url) {

    const fileId = getDriveFileId(url);

    if (!fileId) {
        return null;
    }

    return `https://drive.google.com/file/d/${fileId}/preview`;
}


/* ========================================
   RENDER PROJECT MEDIA
======================================== */

function renderProjectMedia(project) {

    const contentArea =
        modal.querySelector(
            ".project-modal-content-area"
        );

    contentArea.innerHTML = "";


    if (
        !project.media ||
        project.media.length === 0
    ) {

        contentArea.innerHTML = `
            <div class="project-empty-state">
                <p>
                    Project materials will be added here soon.
                </p>
            </div>
        `;

        return;
    }


    let currentGrid = null;


    project.media.forEach((item) => {


        /* --------------------------------
           SECTION TITLE
        -------------------------------- */

        if (item.type === "section") {

            const sectionTitle =
                document.createElement("div");

            sectionTitle.className =
                "project-media-section";

            sectionTitle.innerHTML = `
                <h3>${item.title}</h3>
            `;

            contentArea.appendChild(
                sectionTitle
            );


            currentGrid =
                document.createElement("div");

            currentGrid.className =
                "project-media-grid";

            contentArea.appendChild(
                currentGrid
            );

            return;
        }


        /* --------------------------------
           CREATE GRID IF NEEDED
        -------------------------------- */

        if (!currentGrid) {

            currentGrid =
                document.createElement("div");

            currentGrid.className =
                "project-media-grid";

            contentArea.appendChild(
                currentGrid
            );
        }


        /* --------------------------------
           IMAGE
        -------------------------------- */

        if (item.type === "image") {

            const imageCard =
                document.createElement("div");

            imageCard.className =
                "project-media-card project-image-card";


            const image =
                document.createElement("img");

            image.src =
                getDriveImageUrl(
                    item.url
                );

            image.alt =
                `${project.title} project work`;

            image.loading = "lazy";


            imageCard.appendChild(
                image
            );


            imageCard.addEventListener(
                "click",
                () => {

                    openImageLightbox(
                        image.src
                    );

                }
            );


            currentGrid.appendChild(
                imageCard
            );

            return;
        }


        /* --------------------------------
           VIDEO
        -------------------------------- */

        if (item.type === "video") {

            const videoCard =
                document.createElement("div");

            videoCard.className =
                "project-media-card project-video-card";


            const iframe =
                document.createElement("iframe");

            iframe.src =
                getDriveVideoUrl(
                    item.url
                );

            iframe.loading =
                "lazy";

            iframe.allow =
                "autoplay; encrypted-media; fullscreen";

            iframe.setAttribute(
                "allowfullscreen",
                ""
            );


            videoCard.appendChild(
                iframe
            );


            currentGrid.appendChild(
                videoCard
            );

        }

    });

}


