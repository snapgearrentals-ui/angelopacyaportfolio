/* =========================================================
   PROJECT MODAL
   ========================================================= */

function createProjectModal() {
  if (document.getElementById("apProjectModal")) return;

  const modal = document.createElement("div");

  modal.id = "apProjectModal";

  modal.innerHTML = `
    <div class="ap-project-window">

      <button
        class="ap-project-close"
        type="button"
        aria-label="Close project"
        data-close-project
      >
        ×
      </button>

      <div id="apProjectContent"></div>

    </div>
  `;

  document.body.appendChild(modal);

  modal.addEventListener("click", function(event) {
    if (event.target === modal) {
      closeProject();
    }
  });

  modal.addEventListener("click", function(event) {
    if (event.target.closest("[data-close-project]")) {
      closeProject();
    }
  });
}


/* =========================================================
   RENDER PROJECT
   ========================================================= */

function openProject(projectKey) {
  const project = PROJECTS[projectKey];

  if (!project) {
    console.warn("Project not found:", projectKey);
    return;
  }

  createProjectModal();

  const modal = document.getElementById("apProjectModal");
  const content = document.getElementById("apProjectContent");

  const total = project.media.length;

  const graphicsCount = project.media.filter(
    item => item.category === "graphics"
  ).length;

  const videosCount = project.media.filter(
    item => item.category === "videos"
  ).length;

  content.innerHTML = `
    <div class="ap-project-header">

      <div class="ap-project-eyebrow">
        ${escapeHTML(project.eyebrow)}
      </div>

      <h2 class="ap-project-title">
        ${escapeHTML(project.title)}
      </h2>

      <p class="ap-project-description">
        ${escapeHTML(project.description)}
      </p>

    </div>

    <div class="ap-gallery-top">

      <div class="ap-gallery-heading-row">

        <div class="ap-gallery-heading">
          SELECTED WORK
        </div>

        <div class="ap-gallery-count">
          ${total} ${total === 1 ? "PIECE" : "PIECES"}
        </div>

      </div>

      ${
        total > 0
          ? `
            <div class="ap-filter-bar">

              <button
                class="ap-filter is-active"
                type="button"
                data-filter="all"
              >
                ALL ${total}
              </button>

              ${
                graphicsCount > 0
                  ? `
                    <button
                      class="ap-filter"
                      type="button"
                      data-filter="graphics"
                    >
                      GRAPHICS ${graphicsCount}
                    </button>
                  `
                  : ""
              }

              ${
                videosCount > 0
                  ? `
                    <button
                      class="ap-filter"
                      type="button"
                      data-filter="videos"
                    >
                      VIDEOS ${videosCount}
                    </button>
                  `
                  : ""
              }

            </div>
          `
          : ""
      }

    </div>

    <div class="ap-gallery" id="apGallery">
      ${renderGallery(project.media, "all")}
    </div>
  `;

  modal.classList.add("is-open");
  document.body.style.overflow = "hidden";

  setupProjectFilters(project.media);
  setupGalleryClicks(project.media);
}


/* =========================================================
   GALLERY RENDERER
   ========================================================= */

function renderGallery(media, filter) {
  const filtered =
    filter === "all"
      ? media
      : media.filter(item => item.category === filter);

  if (!media.length) {
    return `
      <div class="ap-no-media">
        Selected project materials will be added here.
      </div>
    `;
  }

  if (!filtered.length) {
    return `
      <div class="ap-no-results">
        No work available in this category yet.
      </div>
    `;
  }

  return filtered
    .map((item, index) => {
      const originalIndex = media.indexOf(item);

      if (item.type === "video") {
        return `
          <div
            class="ap-media-card"
            data-media-index="${originalIndex}"
            data-media-type="video"
          >

            <div class="ap-media-label">
              VIDEO
            </div>

            <img
              src="${driveImage(item.id)}"
              alt="Video project preview"
              loading="lazy"
              onerror="this.style.opacity='0';"
            />

            <div class="ap-media-overlay">
              <span class="ap-media-open">
                Watch video
              </span>

              <span class="ap-video-play">
                ▶
              </span>
            </div>

          </div>
        `;
      }

      return `
        <div
          class="ap-media-card"
          data-media-index="${originalIndex}"
          data-media-type="image"
        >

          <div class="ap-media-label">
            GRAPHIC
          </div>

          <img
            src="${driveImage(item.id)}"
            alt="Portfolio creative work"
            loading="lazy"
            onerror="this.style.opacity='0';"
          />

          <div class="ap-media-overlay">
            <span class="ap-media-open">
              View full image
            </span>
          </div>

        </div>
      `;
    })
    .join("");
}


/* =========================================================
   FILTERS
   ========================================================= */

function setupProjectFilters(media) {
  const modal = document.getElementById("apProjectModal");

  if (!modal) return;

  const filterButtons = modal.querySelectorAll(".ap-filter");
  const gallery = modal.querySelector("#apGallery");

  filterButtons.forEach(button => {
    button.addEventListener("click", function() {
      const filter = button.dataset.filter;

      filterButtons.forEach(btn => {
        btn.classList.remove("is-active");
      });

      button.classList.add("is-active");

      gallery.innerHTML = renderGallery(media, filter);

      setupGalleryClicks(media);
    });
  });
}


/* =========================================================
   GALLERY CLICK
   ========================================================= */

function setupGalleryClicks(media) {
  const gallery = document.getElementById("apGallery");

  if (!gallery) return;

  gallery.querySelectorAll(".ap-media-card").forEach(card => {
    card.addEventListener("click", function() {
      const index = Number(card.dataset.mediaIndex);

      if (!Number.isNaN(index) && media[index]) {
        openLightbox(media[index]);
      }
    });
  });
}


/* =========================================================
   CLOSE PROJECT
   ========================================================= */

function closeProject() {
  const modal = document.getElementById("apProjectModal");

  if (!modal) return;

  modal.classList.remove("is-open");
  document.body.style.overflow = "";
}


