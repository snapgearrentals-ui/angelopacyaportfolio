function driveImage(id) {
  return `https://drive.google.com/thumbnail?id=${id}&sz=w1600`;
}

function drivePreview(id) {
  return `https://drive.google.com/file/d/${id}/preview`;
}

function escapeHTML(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}


